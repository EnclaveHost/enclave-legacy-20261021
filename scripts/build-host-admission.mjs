// The Windows node installs npm dependencies inside windows/node. Bundle shared
// network code there so its sibling modules never resolve absent root packages.
import {build} from 'esbuild';
import fs from 'node:fs/promises';
const file='windows/node/host-admission.bundle.mjs';
const result=await build({entryPoints:['network/host-admission-runtime.mjs'],outfile:file,write:false,
  bundle:true,platform:'node',format:'esm',target:'node20',minify:true,
  banner:{js:'// Generated by scripts/build-host-admission.mjs; edit network/host-admission-runtime.mjs.'}});
const bytes=result.outputFiles[0].contents;
if(process.argv.includes('--check')){
  if(!Buffer.from(bytes).equals(await fs.readFile(file)))throw Error('host admission bundle is stale; run node scripts/build-host-admission.mjs');
}else await fs.writeFile(file,bytes);
